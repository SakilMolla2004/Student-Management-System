package ams.model;

public class ModelSemester {
	int sem_id;
	String sem_code;
	String sem_name;
	String year_code;
	public int getSem_id() {
		return sem_id;
	}
	public void setSem_id(int sem_id) {
		this.sem_id = sem_id;
	}
	public String getSem_code() {
		return sem_code;
	}
	public void setSem_code(String sem_code) {
		this.sem_code = sem_code;
	}
	public String getSem_name() {
		return sem_name;
	}
	public void setSem_name(String sem_name) {
		this.sem_name = sem_name;
	}
	public String getYear_code() {
		return year_code;
	}
	public void setYear_code(String year_code) {
		this.year_code = year_code;
	}
	

}
